func eq[T comparable](t *testing.T, name string, got, want T) {
	t.Helper()
	if got != want {
		t.Errorf("%s: got %v, want %v", name, got, want)
	}
}

func mustSession(t *testing.T, report Report, id string) Session {
	t.Helper()
	s := sessionByID(report, id)
	if s == nil {
		t.Fatalf("no session %s in %d sessions", id, len(report.Sessions))
	}
	return *s
}

