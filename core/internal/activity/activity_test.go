func TestIncrementalRead(t *testing.T) { // Swift: "a second read with the same engine folds only appended bytes and sees the new state"
	sb := newSandbox(t)
	c := claudeRecords{cwd: "/work/app", session: activitySid(121)}
	sb.status(121, obj{"status": "busy"})
	first := []obj{c.user("start", activityNowMs-9000), c.tool("i1", "Bash", obj{"command": "make"}, activityNowMs-8000)}
	path := sb.claudeLog("/work/app", activitySid(121), first, 1000)
	engine := NewEngine()
	p := newFakeProc([]int{121}, nil, nil)
	read := func() Report {
		r, err := engine.Read(context.Background(), sb.roots, activityNow, p, DefaultOptions())
		if err != nil {
			t.Fatal(err)
		}
		return r
	}
	a1 := read()
	eq(t, "tool open", mustSession(t, a1, activitySid(121)).CurrentTool.Name, "Bash")
	// the same file read again without a change must not fold its lines a second time
	f, err := os.OpenFile(path, os.O_APPEND|os.O_WRONLY, 0)
	if err != nil {
		t.Fatal(err)
	}
	_, _ = f.WriteString(activityJSON(c.result("i1", "Exit code 1\nError: nope", true, activityNowMs-500)) + "\n")
	_ = f.Close()
	a2 := read()
	if mustSession(t, a2, activitySid(121)).CurrentTool != nil {
		t.Error("the result closes the tool")
	}
	if len(a2.Failures) != 1 || a2.Failures[0].Title != "make" || a2.Failures[0].Count != 1 {
		t.Errorf("failures = %+v", a2.Failures)
	}
	a3 := read()
	eq(t, "an unchanged log is not folded again", a3.Failures[0].Count, 1)
	if !reflect.DeepEqual(a3, a2) {
		t.Error("a third read of an unchanged log differs from the second")
	}
}

func TestCodexTokenTotals(t *testing.T) { // Swift: "Codex tokens: interleaved streams, repeated totals and an inherited first total do not inflate the count"
	event := func(total [2]int, last *[2]int) []byte {
		info := obj{"total_token_usage": obj{"input_tokens": total[0], "cached_input_tokens": 0, "output_tokens": total[1]}}
		if last != nil {
			info["last_token_usage"] = obj{"input_tokens": last[0], "cached_input_tokens": 0, "output_tokens": last[1]}
		}
		return []byte(activityJSON(obj{"timestamp": activityIso(activityNowMs), "type": "event_msg", "payload": obj{"type": "token_count", "info": info}}))
	}
	metrics := func(lines ...[]byte) usage {
		st := newLogState(CLICodex)
		for _, l := range lines {
			foldCodex(st, l)
		}
		u, _ := st.metrics.Get("unknown")
		return u
	}
	pair := func(a, b int) *[2]int { return &[2]int{a, b} }
	// A parent at 1000, an embedded reviewer's own total at 50, the parent again at 1100, and a repeat of that total.
	m := metrics(event([2]int{1000, 100}, pair(1000, 100)), event([2]int{50, 5}, pair(50, 5)), event([2]int{1100, 110}, pair(100, 10)), event([2]int{1100, 110}, pair(100, 10)))
	if m.Input != 1150 || m.Output != 115 {
		t.Errorf("interleaved: %+v", m)
	}
	// A forked rollout starts from the parent's total: only the turn's own usage belongs to it.
	fork := metrics(event([2]int{90_000, 9000}, pair(200, 20)))
	if fork.Input != 200 || fork.Output != 20 {
		t.Errorf("fork: %+v", fork)
	}
	// Rollouts with no per-turn usage still work from the difference, and a lower total is a restart.
	old := metrics(event([2]int{1000, 100}, nil), event([2]int{1500, 150}, nil), event([2]int{40, 4}, nil))
	if old.Input != 1540 || old.Output != 154 {
		t.Errorf("old: %+v", old)
	}
}
