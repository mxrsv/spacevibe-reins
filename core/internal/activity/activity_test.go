func TestClaudeStates(t *testing.T) { // Swift: ActivityTests.swift "Claude: each state comes from the status file and the transcript tail"
	sb := newSandbox(t)
	quiet := DefaultOptions().ToolQuietMs
	ended := DefaultOptions().EndedKeepMs
	for _, c := range []struct {
		n      int
		status string
		age    float64
	}{{1, "busy", 1000}, {2, "busy", quiet + 60_000}, {4, "idle", 400_000}, {5, "shell", 2000}, {6, "busy", 60_000}, {7, "busy", ended + 60_000}, {8, "busy", 2000}, {9, "mystery", 2000}} {
		sb.status(c.n, obj{"status": c.status})
		sb.claudeLog("/work/app", activitySid(c.n), openClaude(c.n, nil), c.age)
	}
	q := claudeRecords{cwd: "/work/app", session: activitySid(3)}
	sb.status(3, obj{"status": "busy"})
	sb.claudeLog("/work/app", activitySid(3), []obj{q.user("Plan it", activityNowMs-9000), q.tool("q3", "AskUserQuestion", obj{"question": "Which one?"}, activityNowMs-8000)}, 5000)
	p := newFakeProc([]int{1, 2, 3, 4, 5, 8, 9}, map[int]string{8: "Tue Nov  3 01:00:00 2026", 1: "Mon Nov  2  11:00:00  2026"}, nil)
	report := sb.read(p)

	s1 := mustSession(t, report, activitySid(1))
	eq(t, "1 state", s1.State, StateRunning)
	eq(t, "1 tool", s1.CurrentTool.Name, "Bash")
	s2 := mustSession(t, report, activitySid(2))
	eq(t, "2 state", s2.State, StateUnmeasurable)
	eq(t, "2 reason", *s2.ReasonCode, ReasonClaudePromptVsBusy)
	eq(t, "2 text", s2.StateReason, ReasonClaudePromptVsBusy.Text())
	eq(t, "2 tool", s2.CurrentTool.Name, "Bash")
	eq(t, "3 state", mustSession(t, report, activitySid(3)).State, StateWaiting)
	s4 := mustSession(t, report, activitySid(4))
	eq(t, "4 state", s4.State, StateIdle)
	if s4.CurrentTool != nil {
		t.Error("4: an idle session has no current tool")
	}
	eq(t, "5 state", mustSession(t, report, activitySid(5)).State, StateRunning)
	eq(t, "6 state", mustSession(t, report, activitySid(6)).State, StateEnded)
	if sessionByID(report, activitySid(7)) != nil {
		t.Error("7: an ended session older than the keep time is dropped")
	}
	eq(t, "8 reused pid has another start time", mustSession(t, report, activitySid(8)).State, StateEnded)
	eq(t, "9 reason", *mustSession(t, report, activitySid(9)).ReasonCode, ReasonClaudeUnknownStatus)
	// age comes from the transcript's last write, not from the stale statusUpdatedAt
	eq(t, "lastWriteAgoMs", *s1.LastWriteAgoMs, 1000.0)
	eq(t, "ageMs", *s1.AgeMs, 3_600_000.0)
}

