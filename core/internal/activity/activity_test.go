func TestCosts(t *testing.T) { // Swift: "cost: estimated from logged tokens, deduplicated, and nil when the model has no price"
	sb := newSandbox(t)
	now := activityNowMs
	usage := obj{"input_tokens": 1000, "output_tokens": 2000, "cache_creation_input_tokens": 4000, "cache_read_input_tokens": 10_000}
	c := claudeRecords{cwd: "/work/app", session: activitySid(61)}
	sb.status(61, nil)
	sb.claudeLog("/work/app", activitySid(61), []obj{
		c.user("go", now-9000), c.toolWith("a", "Read", obj{"file_path": "/x"}, now-8000, "claude-sonnet-4-6", usage, ""),
		c.toolWith("a2", "Read", obj{"file_path": "/y"}, now-7900, "claude-sonnet-4-6", usage, "msg-a"), // the same message streamed again
		c.toolWith("b", "Read", obj{"file_path": "/z"}, now-7000, "claude-sonnet-4-6", obj{"input_tokens": 500, "output_tokens": 100}, ""),
	}, 0)
	sb.status(62, nil)
	sb.claudeLog("/work/app", activitySid(62), []obj{claudeRecords{cwd: "/work/app", session: activitySid(62)}.toolWith("a", "Read", obj{"file_path": "/x"}, now-8000, "claude-mystery-9", usage, "")}, 0)
	x := codexRecords{id: activityUUID(63)}
	sb.codexLog(activityUUID(63), []obj{x.meta(now-9000, "/work/x", nil), x.model(now-8900, "gpt-6.1-sol"), x.started(now - 8000), x.tokens(now-7000, 10_000, 4000, 500), x.tokens(now-6000, 12_000, 5000, 800), x.done(now - 5000)}, 0)
	report := sb.read(newFakeProc([]int{61, 62}, nil, []proc.Thread{{Pid: 63, ThreadID: activityUUID(63)}}))

	claude := mustSession(t, report, activitySid(61))
	eq(t, "estimated", claude.Cost.Estimated, true)
	// (1000*3 + 2000*15 + 4000*3.75 + 10000*0.3 + 500*3 + 100*15) per million at claude-sonnet-4-6 prices
	approx(t, "claude usd", claude.Cost.USD, 0.054)
	unpriced := mustSession(t, report, activitySid(62))
	if unpriced.Cost != nil {
		t.Error("an unpriced model has no cost")
	}
	// S-R3 finding: the note quotes the model name from the log, as Swift does.
	eq(t, "unpriced note", *unpriced.CostNote, `No price for model "claude-mystery-9", so no estimate.`)
	// gpt-6.1-sol: uncached input 7000*2 + cached 5000*0.1 + output 800*10 per million
	approx(t, "codex usd", mustSession(t, report, activityUUID(63)).Cost.USD, 0.0225)
}

