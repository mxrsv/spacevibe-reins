	sb.status(23, obj{"startedAt": 1_793_440_800_000.0})
	sb.claudeLog("/work/app", activitySid(23), []obj{claudeRecords{cwd: "/work/app", session: activitySid(23)}.user("/review", activityNowMs-8000)}, 0)
	sb.status(24, obj{"name": "Named by the user", "nameSource": "user"})
