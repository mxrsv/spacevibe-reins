	eq(t, "45 state", mustSession(t, report, activityUUID(45)).State, StateWaiting)
	if sessionByID(report, activityUUID(46)) != nil {
		t.Error("a child thread is not a session")
	}
	missing := mustSession(t, report, activityUUID(47))
	eq(t, "47 reason", *missing.ReasonCode, ReasonCodexNoRollout)
