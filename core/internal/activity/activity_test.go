	mk(46, []obj{c(46).meta(now-90_000, "/work/f", obj{"parent_thread_id": activityUUID(41), "source": obj{"subagent": obj{"thread_spawn": obj{"parent_thread_id": activityUUID(41)}}}}), c(46).started(now - 80_000)}, 1000)
	threads = append(threads, proc.Thread{Pid: 4047, ThreadID: activityUUID(47)}, proc.Thread{Pid: 4048})
	report := sb.read(newFakeProc(nil, map[int]string{4047: "Mon Nov  2 11:00:00 2026"}, threads))

	s41 := mustSession(t, report, activityUUID(41))
	eq(t, "41 state", s41.State, StateRunning)
	eq(t, "41 tool", s41.CurrentTool.Name, "exec_command")
