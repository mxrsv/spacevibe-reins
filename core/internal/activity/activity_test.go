	eq(t, "bare reason", *bare.ReasonCode, ReasonCodexNoRollout)
	if bare.LastWriteAgoMs != nil {
		t.Error("a row with no rollout has no last write")
	}
	eq(t, "41 lastWriteAgoMs", *s41.LastWriteAgoMs, 2000.0)
	eq(t, "41 ageMs", *s41.AgeMs, 90_000.0)
