import SwiftUI

/// The marks that stand beside model and CLI names on Tokens (spec, Interface: Tokens): the Claude mark for Claude Code
/// and Anthropic models, the Codex blossom for Codex, the OpenAI mark for OpenAI models. The paths are the ones in
/// `mocks/tokens-board/mock-shell/tokens-logos.js` (copied there from the spacevibe-bench and spacevibe-board brand files),
/// converted once to absolute move, line, cubic and close commands in a 24 by 24 box, arcs as cubics, so no SVG parser is
/// needed at run time. Decorative: the name next to a mark is what VoiceOver reads.
enum ProviderMarkKind: Hashable {
    case claude, codex, openai

    init(cli: CLIKind) { self = cli == .claude ? .claude : .codex }

    /// The mark of a model logged by `cli`; nil for a model the log did not name.
    static func model(_ name: String, cli: CLIKind) -> ProviderMarkKind? {
        name == "unknown" ? nil : (cli == .claude ? .claude : .openai)
    }

    var color: Color {
        switch self {
        case .claude: Palette.claude
        case .codex: Palette.codex
        case .openai: Palette.text
        }
    }

    fileprivate var path: Path {
        switch self {
        case .claude: MarkPaths.claude
        case .codex: MarkPaths.codex
        case .openai: MarkPaths.openai
        }
    }
}

struct ProviderMark: View {
    let kind: ProviderMarkKind
    var size: CGFloat = 14

    init(_ kind: ProviderMarkKind, size: CGFloat = 14) {
        self.kind = kind
        self.size = size
    }

    var body: some View {
        MarkShape(unit: kind.path)
            .fill(kind.color, style: FillStyle(eoFill: true))
            .frame(width: size, height: size)
            .accessibilityHidden(true)
    }
}

private struct MarkShape: Shape {
    let unit: Path

    func path(in rect: CGRect) -> Path {
        let scale = min(rect.width, rect.height) / MarkPaths.box
        return unit.applying(CGAffineTransform(scaleX: scale, y: scale).concatenating(CGAffineTransform(translationX: rect.minX, y: rect.minY)))
    }
}

private enum MarkPaths {
    static let box: CGFloat = 24
    static let claude = parse(CLAUDE)
    static let codex = parse(CODEX)
    static let openai = parse(OPENAI)

    /// `M x y`, `L x y`, `C x1 y1 x2 y2 x y` and `Z`, absolute, numbers separated by spaces or by the next command.
    static func parse(_ data: String) -> Path {
        var path = Path()
        var command: Character = "M"
        var numbers: [CGFloat] = []
        var token = ""
        func flushNumber() {
            if let value = Double(token) { numbers.append(CGFloat(value)) }
            token = ""
        }
        func flushCommand() {
            flushNumber()
            let n = numbers
            switch command {
            case "M" where n.count == 2: path.move(to: CGPoint(x: n[0], y: n[1]))
            case "L" where n.count == 2: path.addLine(to: CGPoint(x: n[0], y: n[1]))
            case "C" where n.count == 6:
                path.addCurve(to: CGPoint(x: n[4], y: n[5]), control1: CGPoint(x: n[0], y: n[1]), control2: CGPoint(x: n[2], y: n[3]))
            case "Z": path.closeSubpath()
            default: break
            }
            numbers = []
        }
        for ch in data {
            switch ch {
            case "M", "L", "C", "Z":
                flushCommand()
                command = ch
            case " ", "\n":
                flushNumber()
            default:
                token.append(ch)
            }
        }
        flushCommand()
        return path
    }

